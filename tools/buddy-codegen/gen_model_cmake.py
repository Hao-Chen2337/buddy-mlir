#!/usr/bin/env python3
"""Render each decoder-only family's ``models/<family>/CMakeLists.txt``.

The per-family build used to be a ~100-line hand-copied ``CMakeLists.txt`` that
differed from family to family only by its cache-variable prefix, its Mode A/B
dir prefix and its default variant spec.  ``buddy_add_decoder_model`` (in
``cmake/buddy_decoder_model.cmake``) now encapsulates that boilerplate, so a
family's ``CMakeLists.txt`` is just a one-line call to it:

    buddy_add_decoder_model(NAME qwen25 PREFIX QWEN25 UPPER QWEN25
                            DEFAULT_SPEC f16.json DISPLAY "Qwen2.5"
                            VOCAB examples/BuddyDeepSeekR1/vocab.txt)

This script derives every argument of that call from
``decoder_models.DECODER_MODELS``, so adding a decoder model is: add one entry
there + add ``models/<family>/specs/*.json``, then re-run this script.

Usage:
    python3 gen_model_cmake.py [--write] [--check] [--families qwen25,llama]

``--write`` (default) regenerates every family's ``CMakeLists.txt`` in place.
``--check`` only reports which files would change (exit 0 = up to date).
"""

import argparse
import difflib
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from decoder_models import DECODER_MODELS  # noqa: E402

REPO_ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))

HEADER = """\
# ── {display} ({family}) ────────────────────────────────────────────────────
# Generated by tools/buddy-codegen/gen_model_cmake.py -- do not edit by hand.
# Add/change this family in tools/buddy-codegen/decoder_models.py, then run:
#     python3 tools/buddy-codegen/gen_model_cmake.py
# {note}
# ─────────────────────────────────────────────────────────────────────────────
include(${{CMAKE_SOURCE_DIR}}/tools/buddy-codegen/cmake/buddy_decoder_model.cmake)
buddy_add_decoder_model(
  NAME {family} PREFIX {prefix} UPPER {upper}
  DEFAULT_SPEC {default_spec} DISPLAY {display_q}{vocab_line})
"""


def render(family, entry):
    vocab = entry.get("vocab")
    vocab_line = f"\n  VOCAB {vocab}" if vocab else ""
    return HEADER.format(
        family=family,
        display=entry["display"],
        prefix=entry["cmake_prefix"],
        upper=entry["cmake_upper"],
        default_spec=entry["default_spec"],
        note=entry.get("note", ""),
        display_q=json.dumps(entry["display"]),
        vocab_line=vocab_line,
    )


def cmake_path(family):
    return os.path.join(REPO_ROOT, "models", family, "CMakeLists.txt")


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument(
        "--write",
        action="store_true",
        help="regenerate CMakeLists.txt in place (default)",
    )
    ap.add_argument(
        "--check",
        action="store_true",
        help="only report files that would change",
    )
    ap.add_argument(
        "--families",
        default="",
        help="comma-separated family subset (default: all registered families)",
    )
    args = ap.parse_args()

    chosen = (
        [f.strip() for f in args.families.split(",") if f.strip()]
        if args.families
        else list(DECODER_MODELS)
    )

    changed = []
    for family in chosen:
        entry = DECODER_MODELS[family]
        if "cmake_prefix" not in entry or "cmake_upper" not in entry:
            print(
                f"SKIP {family}: missing cmake_prefix/cmake_upper",
                file=sys.stderr,
            )
            continue

        target = cmake_path(family)
        new_text = render(family, entry)

        if os.path.exists(target):
            with open(target, encoding="utf-8") as f:
                old_text = f.read()
            if old_text == new_text:
                continue
            changed.append(family)
            if args.check:
                diff = difflib.unified_diff(
                    old_text.splitlines(keepends=True),
                    new_text.splitlines(keepends=True),
                    fromfile=target,
                    tofile=target + " (generated)",
                )
                sys.stdout.writelines(diff)
                continue
        else:
            changed.append(family)

        if args.write or not args.check:
            os.makedirs(os.path.dirname(target), exist_ok=True)
            with open(target, "w", encoding="utf-8") as f:
                f.write(new_text)
            print(f"wrote {os.path.relpath(target, REPO_ROOT)}")

    if args.check:
        if changed:
            print(
                f"{len(changed)} family CMakeLists.txt out of date: "
                + ", ".join(changed),
                file=sys.stderr,
            )
            return 1
        print("all decoder CMakeLists.txt up to date")
        return 0
    return 0


if __name__ == "__main__":
    sys.exit(main())
